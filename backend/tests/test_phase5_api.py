# ---------------------------------------------------------------- T24: errors
def test_t24_error_surface(client, monkeypatch):
    r = client.get("/api/runs/zzzzzz99/result")
    assert r.status_code == 404
    body = r.json()
    assert body["code"] == "RUN_NOT_FOUND" and "zzzzzz99" in body["message"]

    r = client.post("/api/runs", json={"attack": "replay", "message": "x"})
    assert r.status_code == 400 and r.json()["code"] == "INVALID_PARAMS"

    r = client.post("/api/runs", json={"attack": "warp-drive", "message": "x"})
    assert r.status_code == 400 and r.json()["code"] == "INVALID_PARAMS"

    r = client.post("/api/runs/zzzzzz99/rerun", json={})
    assert r.status_code == 404 and r.json()["code"] == "RUN_NOT_FOUND"

    # forced engine crash -> 500 BACKEND_ERROR + FAILED row + 412 on later reads
    from app.api import routes as R

    def boom(*a, **k):
        raise RuntimeError("synthetic engine crash")

    monkeypatch.setattr(R.pipeline, "run", boom)
    r = client.post("/api/runs", json={"attack": "no-attack", "message": "CRASH ME"})
    assert r.status_code == 500
    body = r.json()
    assert body["code"] == "BACKEND_ERROR" and "detail" in body
    monkeypatch.undo()

    from app.db import db as kit
    from app.db.models import Run
    from sqlalchemy import select
    with kit.transaction() as s:
        row = s.execute(select(Run).where(Run.message == "CRASH ME")
                        .order_by(Run.created_at.desc())).scalars().first()
        assert row is not None and row.status == "FAILED"
        failed_sid = row.session_id
    r = client.get(f"/api/runs/{failed_sid}/result")
    assert r.status_code == 412 and r.json()["code"] == "INVALID_STATE"
    r = client.get(f"/api/runs/{failed_sid}/events")
    assert r.status_code == 412


