def test_t22_tsc_crosscheck_real_json_against_types_ts(client):
    """Real backend JSON, embedded as fresh literals, must `satisfies` the
    frontend's own types. Excess keys or wrong unions fail compilation."""
    result = client.get("/api/runs/honest7/result").json()
    forged = client.get("/api/runs/e4f5a1/result").json()
    system = client.get("/api/system").json()
    history = client.get("/api/history").json()
    events = []
    with client.stream("GET", "/api/runs/j8k3w9/events") as s:
        buf = ""
        for chunk in s.iter_text():
            buf += chunk
        for frame in buf.split("\n\n"):
            for line in frame.split("\n"):
                if line.startswith("data:"):
                    events.append(json.loads(line[5:].strip()))

    ts = f"""// generated by test_phase5_api — do not commit
import type {{ ResultResponse, RunEvent, HistoryResponse, SystemResponse }} from "./src/api/types";
const honest = {json.dumps(result)} satisfies ResultResponse;
const forged = {json.dumps(forged)} satisfies ResultResponse;
const sys = {json.dumps(system)} satisfies SystemResponse;
const hist = {json.dumps(history)} satisfies HistoryResponse;
const evs = {json.dumps(events)} satisfies RunEvent[];
export {{ honest, forged, sys, hist, evs }};
"""
    out = FRONTEND / "wire-check.generated.ts"
    cfg = FRONTEND / "tsconfig.wirecheck.json"
    out.write_text(ts)
    cfg.write_text(json.dumps({
        "extends": "./tsconfig.app.json",
        "include": ["wire-check.generated.ts", "src/api/types.ts"],
        "compilerOptions": {"noEmit": True, "strict": True},
    }))
    try:
        proc = subprocess.run(["npx", "tsc", "-p", str(cfg)],
                              cwd=FRONTEND, capture_output=True, text=True,
                              timeout=300)
        assert proc.returncode == 0, proc.stdout + proc.stderr
    finally:
        out.unlink(missing_ok=True)
        cfg.unlink(missing_ok=True)


# ---------------------------------------------------------------- T23: SSE
def test_t23_sse_order_headers_done(client):
    r = client.get("/api/runs/honest7/events")
    assert r.headers["content-type"].startswith("text/event-stream")
    assert r.headers["cache-control"] == "no-cache"
    assert r.headers["x-accel-buffering"] == "no"
    frames = [json.loads(l[5:].strip()) for l in r.text.split("\n")
              if l.startswith("data:")]
    assert frames[0]["kind"] == "session"
    assert frames[-1]["kind"] == "done"
    ts = [f["tMs"] for f in frames]
    assert ts == sorted(ts), "tMs must be non-decreasing in stream order"
    kinds = [f["kind"] for f in frames]
    assert kinds.count("verify-bag") == 126  # 63 bags x 2 verifiers
    # matches the DB byte-for-byte, in order
    from app.db import db as kit
    from app.db import repository as repo
    with kit.transaction() as s:
        assert frames == repo.events_of(s, "honest7")


def test_t23_disconnect_stops_stream():
    """The generator must stop (not keep yielding) once the client is gone."""
    from app.api.routes import events

    class GoneRequest:
        async def is_disconnected(self):
            return True

    resp = asyncio.run(events("honest7", GoneRequest()))

    async def drain():
        return [chunk async for chunk in resp.body_iterator]

    chunks = asyncio.run(drain())
    assert len(chunks) == 0, "stream kept yielding after disconnect"


